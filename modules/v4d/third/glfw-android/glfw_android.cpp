void glfw_android_set_input_queue(AInputQueue *queue) {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  // This is called from the UI thread, which is not the thread that polls, so the
  // attach is deferred to inputLooper() on the first poll. The queue can be
  // attached to a looper owned by another thread as long as that thread polls
  // it; what it cannot do is be polled from here.
  p.inputQueue = queue;
  if (!queue) {
    p.looper = nullptr;
    return;
  }
  if (p.looper)
    AInputQueue_attachLooper(queue, p.looper, kInputQueueIdent, nullptr, nullptr);
}

