// There is no desktop to ask about, but FrameBufferContext wants a size before
// the first frame, so report whatever the surface says once it exists.
void refreshDisplayMode() {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  int width = 0, height = 0;
  if (p.nativeWindow) {
    width = ANativeWindow_getWidth(p.nativeWindow);
    height = ANativeWindow_getHeight(p.nativeWindow);
  }
  if (width <= 0 || height <= 0) {
    // No surface yet. ANativeActivity has no configuration field, so fall back
    // to the display size the platform already reported; zero if even that is
    // unknown, which the caller treats as "ask again once a surface exists".
    if (p.displayWidthPx > 0 && p.displayHeightPx > 0) {
      width = p.displayWidthPx;
      height = p.displayHeightPx;
    }
  }
  p.primaryMonitor.mode.width = width;
  p.primaryMonitor.mode.height = height;
}

void glfwGetDesktopMode(int *width, int *height) {
  refreshDisplayMode();
  Platform &p = platform();
  if (width)
    *width = p.primaryMonitor.mode.width;
  if (height)
    *height = p.primaryMonitor.mode.height;
}

void glfwGetDesktopModeLimits(int *minWidth, int *minHeight, int *maxWidth,
                              int *maxHeight) {
  int width = 0, height = 0;
  glfwGetDesktopMode(&width, &height);
  if (minWidth)
    *minWidth = 1;
  if (minHeight)
    *minHeight = 1;
  if (maxWidth)
    *maxWidth = width;
  if (maxHeight)
    *maxHeight = height;
}

void glfwGetDesktopModeRefreshRate(int *refreshRate) {
  // Android does not report one; the compositor paces the display.
  if (refreshRate)
    *refreshRate = 60;
}

