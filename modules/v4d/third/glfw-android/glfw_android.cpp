void glfwWindowHint(int hint, int value) {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  switch (hint) {
  case GLFW_CONTEXT_VERSION_MAJOR: p.hints.contextVersionMajor = value; break;
  case GLFW_CONTEXT_VERSION_MINOR: p.hints.contextVersionMinor = value; break;
  case GLFW_CLIENT_API:
    // ES is the only client API here; note the request and carry on rather than
    // failing a sample that asks for the desktop default.
    if (value != GLFW_OPENGL_ES_API)
      LOGW("GLFW_CLIENT_API is OpenGL ES on Android; ignoring the request");
    break;
  case GLFW_CONTEXT_CREATION_API:
    if (value != GLFW_EGL_CONTEXT_API)
      LOGW("only the EGL context creation API exists on Android");
    break;
  case GLFW_SAMPLES: p.hints.samples = value; break;
  case GLFW_RESIZABLE: p.hints.resizable = value != GLFW_FALSE; break;
  case GLFW_VISIBLE: p.hints.visible = value != GLFW_FALSE; break;
  case GLFW_DECORATED: p.hints.decorated = value != GLFW_FALSE; break;
  case GLFW_FOCUSED: p.hints.focused = value != GLFW_FALSE; break;
  // Colours, profile, focus-on-show and the rest have no Android meaning.
  default: break;
  }
}

