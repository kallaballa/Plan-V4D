struct Platform {
  // Recursive because reportError() invokes the user callback, and a GLFW error
  // callback that logs through V4D can re-enter the shim.
  std::recursive_mutex mutex;
  std::condition_variable_any surfaceCv;

  ANativeActivity *activity = nullptr;
  AInputQueue *inputQueue = nullptr;
  ALooper *looper = nullptr;
  ANativeWindow *nativeWindow = nullptr; // weak: the activity owns it
  bool resumed = false;
  uint64_t windowGeneration = 1;

  // The one EGL display of the process, initialised on first use and reference
  // counted: eglGetDisplay hands out the same handle every time, and
  // eglTerminate() invalidates every context and surface on it, so tearing the
  // display down with a child window still alive would take that child down too.
  EGLDisplay display = EGL_NO_DISPLAY;
  int displayUsers = 0;
  int eglMajor = 0;
  int eglMinor = 0;
  // The config is display-scoped and expensive to pick, so it is cached together
  // with the hints that produced it.
  EGLConfig config = nullptr;
  WindowHints configHints{};
  bool configValid = false;

  // Display size in pixels, recorded when the activity reports a configuration
  // change. It is what FrameBufferContext asks for before a surface exists.
  int displayWidthPx = 0;
  int displayHeightPx = 0;

  GlfwAndroidInputHandler inputHandler = nullptr;

  bool initialized = false;
  GLFWerrorfun errorCallback = nullptr;
  int lastError = GLFW_NO_ERROR;
  std::string lastErrorText;

  double timeOffset = 0.0;
  GLFWwindow *currentContext = nullptr;
  GLFWmonitor primaryMonitor;
  GLFWmonitorfun monitorCallback = nullptr;
  GLFWjoystickfun joystickCallback = nullptr;
  std::vector<GLFWwindow *> windows;
  WindowHints hints;
};

Platform gPlatform;

Platform &platform() {
  static Platform instance;
  return instance;
}

// Defined at the bottom, next to the desktop-mode queries that need it. It sits
// inside the extern "C" block with the GLFW entry points, so it has to be
// declared here in an extern "C" block too -- a C++-linkage declaration would
// make every call below ambiguous.
extern "C" void refreshDisplayMode();
void reportError(int code, const char *fmt, ...) {
  Platform &p = platform();
  char buffer[512];
  va_list args;
  va_start(args, fmt);
  vsnprintf(buffer, sizeof(buffer), fmt, args);
  va_end(args);
  p.lastError = code;
  p.lastErrorText = buffer;
  LOGW("error %d: %s", code, buffer);
  if (p.errorCallback)
    p.errorCallback(code, buffer);
}

ANativeWindow *acquireWindowLocked() {
  ANativeWindow *window = platform().nativeWindow;
  if (window)
    ANativeWindow_acquire(window);
  return window;
}

/// The size of whatever a window draws into.
///
/// For the window that owns the activity's ANativeWindow that is the surface
/// itself: Android gives an app the whole screen, so a requested size is not one
/// the platform can honour, and reporting it back anyway would leave V4D
/// blitting its framebuffer into a corner of a drawable it believes is a
/// different size. Offscreen children have no surface at all -- they get an
/// offscreen one of exactly the size they asked for, which is what their
/// framebuffers are sized after.
void drawableSize(GLFWwindow *window, int &width, int &height) {
  width = window ? window->width : 0;
  height = window ? window->height : 0;
  if (window && window->ownsSurface && window->nativeWindow) {
    width = ANativeWindow_getWidth(window->nativeWindow);
    height = ANativeWindow_getHeight(window->nativeWindow);
  }
}

/// Reads the drawable size and announces it if it changed -- a rotation, a
/// resize or a foldable unfolding all show up as a different ANativeWindow size
/// with no event of their own. Called from the frame loop
/// (glfwPollEvents/glfwSwapBuffers), and never from a query: FrameBufferContext
/// asks for the size through glfwGetWindowSize()/glfwGetVideoMode() before the
/// first frame, and re-entering the callback chain from there would be wrong.
///
/// This is also how V4D learns the size at all. The window starts out reporting
/// what was asked for, and the first pass through the frame loop replaces it with
/// the surface's real size and fires the framebuffer-size callback, which is what
/// sets the WINDOW_SIZE property the display path blits into.
void updateSizeAndNotify(GLFWwindow *window) {
  if (!window)
    return;
  int width = 0, height = 0;
  drawableSize(window, width, height);
  if (width == window->width && height == window->height)
    return;
  window->width = width;
  window->height = height;
  if (window->framebufferSizeCallback)
    window->framebufferSizeCallback(window, width, height);
  if (window->sizeCallback)
    window->sizeCallback(window, width, height);
}

int glfwModsFromMetaState(int32_t metaState) {
  int mods = 0;
  if (metaState & AMETA_SHIFT_ON)
    mods |= GLFW_MOD_SHIFT;
  if (metaState & AMETA_CTRL_ON)
    mods |= GLFW_MOD_CONTROL;
  if (metaState & AMETA_ALT_ON)
    mods |= GLFW_MOD_ALT;
  if (metaState & AMETA_META_ON)
    mods |= GLFW_MOD_SUPER;
  return mods;
}

// Android and GLFW number keys differently: GLFW uses printable ASCII for
// letters and digits and a dense range for the function keys. Both families are
// contiguous in AKEYCODE and in the GLFW tokens, so they translate by offset;
// everything else needs an explicit pair.
int glfwKeyFromAndroid(int32_t keycode, int32_t source) {
  if (keycode >= AKEYCODE_A && keycode <= AKEYCODE_Z)
    return GLFW_KEY_A + (keycode - AKEYCODE_A);
  if (keycode >= AKEYCODE_0 && keycode <= AKEYCODE_9)
    return GLFW_KEY_0 + (keycode - AKEYCODE_0);
  if (keycode >= AKEYCODE_F1 && keycode <= AKEYCODE_F12)
    return GLFW_KEY_F1 + (keycode - AKEYCODE_F1);
  if (keycode >= AKEYCODE_NUMPAD_0 && keycode <= AKEYCODE_NUMPAD_9)
    return GLFW_KEY_KP_0 + (keycode - AKEYCODE_NUMPAD_0);

  switch (keycode) {
  case AKEYCODE_SPACE: return GLFW_KEY_SPACE;
  case AKEYCODE_ENTER:
    // The numeric keypad's enter is a different GLFW key.
    return (source == AINPUT_SOURCE_KEYBOARD) ? GLFW_KEY_KP_ENTER : GLFW_KEY_ENTER;
  case AKEYCODE_DEL: return GLFW_KEY_BACKSPACE;
  case AKEYCODE_FORWARD_DEL: return GLFW_KEY_DELETE;
  case AKEYCODE_TAB: return GLFW_KEY_TAB;
  case AKEYCODE_ESCAPE: return GLFW_KEY_ESCAPE;
  case AKEYCODE_MINUS: return GLFW_KEY_MINUS;
  case AKEYCODE_EQUALS: return GLFW_KEY_EQUAL;
  case AKEYCODE_LEFT_BRACKET: return GLFW_KEY_LEFT_BRACKET;
  case AKEYCODE_RIGHT_BRACKET: return GLFW_KEY_RIGHT_BRACKET;
  case AKEYCODE_BACKSLASH: return GLFW_KEY_BACKSLASH;
  case AKEYCODE_SEMICOLON: return GLFW_KEY_SEMICOLON;
  case AKEYCODE_APOSTROPHE: return GLFW_KEY_APOSTROPHE;
  case AKEYCODE_SLASH: return GLFW_KEY_SLASH;
  case AKEYCODE_COMMA: return GLFW_KEY_COMMA;
  case AKEYCODE_PERIOD: return GLFW_KEY_PERIOD;
  case AKEYCODE_GRAVE: return GLFW_KEY_GRAVE_ACCENT;
  case AKEYCODE_MENU: return GLFW_KEY_MENU;
  case AKEYCODE_CAPS_LOCK: return GLFW_KEY_CAPS_LOCK;
  case AKEYCODE_SCROLL_LOCK: return GLFW_KEY_SCROLL_LOCK;
  case AKEYCODE_NUM_LOCK: return GLFW_KEY_NUM_LOCK;
  case AKEYCODE_SYSRQ: return GLFW_KEY_PRINT_SCREEN;
  case AKEYCODE_BREAK: return GLFW_KEY_PAUSE;
  case AKEYCODE_INSERT: return GLFW_KEY_INSERT;
  case AKEYCODE_MOVE_HOME: return GLFW_KEY_HOME;
  case AKEYCODE_MOVE_END: return GLFW_KEY_END;
  case AKEYCODE_PAGE_UP: return GLFW_KEY_PAGE_UP;
  case AKEYCODE_PAGE_DOWN: return GLFW_KEY_PAGE_DOWN;
  case AKEYCODE_DPAD_UP: return GLFW_KEY_UP;
  case AKEYCODE_DPAD_DOWN: return GLFW_KEY_DOWN;
  case AKEYCODE_DPAD_LEFT: return GLFW_KEY_LEFT;
  case AKEYCODE_DPAD_RIGHT: return GLFW_KEY_RIGHT;
  case AKEYCODE_NUMPAD_DOT:
  case AKEYCODE_NUMPAD_COMMA: return GLFW_KEY_KP_DECIMAL;
  case AKEYCODE_NUMPAD_ADD: return GLFW_KEY_KP_ADD;
  case AKEYCODE_NUMPAD_SUBTRACT: return GLFW_KEY_KP_SUBTRACT;
  case AKEYCODE_NUMPAD_MULTIPLY: return GLFW_KEY_KP_MULTIPLY;
  case AKEYCODE_NUMPAD_DIVIDE: return GLFW_KEY_KP_DIVIDE;
  case AKEYCODE_NUMPAD_EQUALS: return GLFW_KEY_KP_EQUAL;
  case AKEYCODE_SHIFT_LEFT: return GLFW_KEY_LEFT_SHIFT;
  case AKEYCODE_SHIFT_RIGHT: return GLFW_KEY_RIGHT_SHIFT;
  case AKEYCODE_CTRL_LEFT: return GLFW_KEY_LEFT_CONTROL;
  case AKEYCODE_CTRL_RIGHT: return GLFW_KEY_RIGHT_CONTROL;
  case AKEYCODE_ALT_LEFT: return GLFW_KEY_LEFT_ALT;
  case AKEYCODE_ALT_RIGHT: return GLFW_KEY_RIGHT_ALT;
  case AKEYCODE_META_LEFT: return GLFW_KEY_LEFT_SUPER;
  case AKEYCODE_META_RIGHT: return GLFW_KEY_RIGHT_SUPER;
  default: return GLFW_KEY_UNKNOWN;
  }
}

/// True for anything that can point at the screen: mouse, finger or stylus.
/// Android reports them all as pointer sources, and an on-screen demo wants them
/// folded onto the same left mouse button.
bool isPointerSource(int32_t source) {
  return (source & AINPUT_SOURCE_CLASS_MASK) == AINPUT_SOURCE_CLASS_POINTER;
}

GLFWwindow *dispatchTarget() {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  if (p.currentContext)
    return p.currentContext;
  for (GLFWwindow *candidate : p.windows) {
    if (candidate->ownsSurface)
      return candidate;
  }
  return p.windows.empty() ? nullptr : p.windows.front();
}

void dispatchKey(GLFWwindow *window, int key, int scancode, int action, int mods) {
  if (!window || key == GLFW_KEY_UNKNOWN)
    return;
  if (action == GLFW_PRESS)
    window->keys[key] = GLFW_PRESS;
  else if (action == GLFW_RELEASE)
    window->keys[key] = GLFW_RELEASE;
  if (window->keyCallback)
    window->keyCallback(window, key, scancode, action, mods);
}

void dispatchMouseButton(GLFWwindow *window, int button, int action, int mods) {
  if (!window)
    return;
  window->buttons[button] = static_cast<unsigned char>(action);
  if (window->mouseButtonCallback)
    window->mouseButtonCallback(window, button, action, mods);
}

void dispatchCursorPos(GLFWwindow *window, double x, double y) {
  if (!window)
    return;
  window->cursorX = x;
  window->cursorY = y;
  if (window->cursorPosCallback)
    window->cursorPosCallback(window, x, y);
}

void dispatchCursorEnter(GLFWwindow *window, bool entered) {
  if (!window)
    return;
  window->cursorInside = entered;
  if (window->cursorEnterCallback)
    window->cursorEnterCallback(window, entered ? GLFW_TRUE : GLFW_FALSE);
}

void dispatchScroll(GLFWwindow *window, double x, double y) {
  if (window && window->scrollCallback)
    window->scrollCallback(window, x, y);
}

void dispatchChar(GLFWwindow *window, uint32_t codepoint, int mods) {
  if (!window)
    return;
  if (window->charCallback)
    window->charCallback(window, codepoint);
  if (window->charModsCallback)
    window->charModsCallback(window, codepoint, mods);
}

/// Blocks until the activity hands over a surface, so that the render thread
/// does not race the UI thread into glfwCreateWindow().
ANativeWindow *waitForNativeWindow() {
  Platform &p = platform();
  std::unique_lock<std::recursive_mutex> lock(p.mutex);
  const auto deadline =
      std::chrono::steady_clock::now() + std::chrono::nanoseconds(kSurfaceWaitNs);
  while (!p.nativeWindow) {
    if (p.surfaceCv.wait_until(lock, deadline) == std::cv_status::timeout &&
        !p.nativeWindow)
      return nullptr;
  }
  return acquireWindowLocked();
}

void handleMotion(GLFWwindow *window, const AInputEvent *event) {
  const int32_t source = AInputEvent_getSource(event);
  if (!isPointerSource(source))
    return; // joystick, sensor, ... not supported

  const int32_t action = AMotionEvent_getAction(event) & AMOTION_EVENT_ACTION_MASK;
  switch (action) {
  case AMOTION_EVENT_ACTION_DOWN:
  case AMOTION_EVENT_ACTION_BUTTON_PRESS:
    dispatchCursorPos(window, AMotionEvent_getX(event, 0), AMotionEvent_getY(event, 0));
    if (!window->cursorInside)
      dispatchCursorEnter(window, true);
    dispatchMouseButton(window, GLFW_MOUSE_BUTTON_LEFT, GLFW_PRESS, 0);
    break;
  case AMOTION_EVENT_ACTION_UP:
  case AMOTION_EVENT_ACTION_BUTTON_RELEASE:
    dispatchMouseButton(window, GLFW_MOUSE_BUTTON_LEFT, GLFW_RELEASE, 0);
    break;
  case AMOTION_EVENT_ACTION_CANCEL:
    dispatchMouseButton(window, GLFW_MOUSE_BUTTON_LEFT, GLFW_RELEASE, 0);
    dispatchCursorPos(window, -1.0, -1.0);
    dispatchCursorEnter(window, false);
    break;
  case AMOTION_EVENT_ACTION_MOVE:
  case AMOTION_EVENT_ACTION_HOVER_MOVE:
    // A drag only reports the pointer that moved; index 0 is the primary one,
    // which is as much as a single-pointer UI can use.
    dispatchCursorPos(window, AMotionEvent_getX(event, 0), AMotionEvent_getY(event, 0));
    if (!window->cursorInside)
      dispatchCursorEnter(window, true);
    break;
  case AMOTION_EVENT_ACTION_HOVER_EXIT:
    dispatchCursorEnter(window, false);
    break;
  case AMOTION_EVENT_ACTION_SCROLL:
    // Android's scroll offsets grow the other way round to GLFW's.
    dispatchScroll(window, -AMotionEvent_getXOffset(event),
                   -AMotionEvent_getYOffset(event));
    break;
  default:
    break;
  }
}

/// The looper the input queue is attached to, prepared on -- and therefore
/// pollable by -- whichever thread first asks for input.
///
/// ALooper_pollOnce() always polls the *calling* thread's looper, so the queue
/// cannot be attached to the UI thread's looper and drained from the render
/// thread: there is no API that polls a looper belonging to another thread.
/// The attachment therefore has to happen on the thread that will poll, which is
/// the one V4D's display thread is on. That is where this is called from.
ALooper *inputLooper() {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  if (!p.looper) {
    p.looper = ALooper_forThread();
    if (!p.looper)
      p.looper = ALooper_prepare(ALOOPER_PREPARE_ALLOW_NON_CALLBACKS);
    if (p.looper && p.inputQueue) {
      AInputQueue_attachLooper(p.inputQueue, p.looper, kInputQueueIdent, nullptr,
                               nullptr);
      LOGI("input queue attached to looper %p on this thread", p.looper);
    }
  }
  return p.looper;
}

/// Drains the input queue, firing the GLFW callbacks. This mirrors the NDK's
/// native_app_glue so the input method still sees the events it wants
/// (preDispatch) and every event is released exactly once.
///
/// \param timeoutMs how long to block waiting for input. 0 is the frame loop's
///        "catch up with whatever arrived"; -1 is glfwWaitEvents()'s "block until
///        something happens". ALooper_pollAll() used to do this in one call and
///        is removed from the NDK, so this is the documented replacement: call
///        pollOnce() in a loop, and treat every non-negative return as "wake".
void pumpInput(int timeoutMs) {
  Platform &p = platform();
  AInputQueue *queue = nullptr;
  GlfwAndroidInputHandler handler = nullptr;
  {
    std::lock_guard<std::recursive_mutex> lock(p.mutex);
    queue = p.inputQueue;
    handler = p.inputHandler;
  }
  if (!queue || !inputLooper())
    return;

  int fd = 0, events = 0;
  void *data = nullptr;
  while (true) {
    const int result = ALooper_pollOnce(timeoutMs, &fd, &events, &data);
    timeoutMs = 0; // only the first call may wait
    if (result < 0)
      return; // this thread has no looper, or the looper is gone
    // Any wakeup counts, not only the ones that carry our identifier -- that is
    // the one thing ALooper_pollAll() did for us and pollOnce() does not.
    if (result != kInputQueueIdent)
      return;

    AInputEvent *event = nullptr;
    while (AInputQueue_getEvent(queue, &event) >= 0) {
      if (AInputQueue_preDispatchEvent(queue, event))
        continue; // the input method consumed it; it finishes itself

      int32_t handled = 0;
      if (handler)
        handled = handler(event);

      GLFWwindow *window = dispatchTarget();
      switch (AInputEvent_getType(event)) {
      case AINPUT_EVENT_TYPE_KEY: {
        const int32_t keycode = AKeyEvent_getKeyCode(event);
        const int32_t source = AInputEvent_getSource(event);
        const int key = glfwKeyFromAndroid(keycode, source);
        const int32_t action = AKeyEvent_getAction(event);
        int glfwAction = GLFW_RELEASE;
        if (action == AKEY_EVENT_ACTION_DOWN) {
          // Auto-repeat arrives as a repeat count on the "down" action, which is
          // GLFW_REPEAT rather than a second press.
          glfwAction =
              AKeyEvent_getRepeatCount(event) > 0 ? GLFW_REPEAT : GLFW_PRESS;
        }
        dispatchKey(window, key, static_cast<int>(AKeyEvent_getScanCode(event)),
                    glfwAction, glfwModsFromMetaState(AKeyEvent_getMetaState(event)));
        // There is no separate "text" event any more: an input method delivers
        // characters as key events with AKEY_EVENT_FLAG_SOFT_KEYBOARD set. The
        // NDK exposes no Unicode accessor for them, so the codepoint comes from
        // ImGui's backend (which is handed the raw events) and from whatever an
        // app derives itself -- see glfw_android.hpp's input handler hook.
        break;
      }
      case AINPUT_EVENT_TYPE_MOTION:
        handleMotion(window, event);
        break;
      default:
        break;
      }
      AInputQueue_finishEvent(queue, event, handled);
    }
  }
}

/// (Re)creates the EGL surface for whatever native window is current. The surface
/// belongs to one ANativeWindow, so coming back from the background -- where the
/// old one was destroyed -- needs a new one.
///
/// Only the window that owns the activity's surface has one; the offscreen
/// children have pbuffers that nothing destroys behind their back.
void refreshSurface(GLFWwindow *window) {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  if (!window || !window->ownsSurface || !p.resumed || !p.nativeWindow)
    return;
  if (window->nativeWindow == p.nativeWindow && window->surface)
    return;

  if (window->surface) {
    eglMakeCurrent(window->display, EGL_NO_SURFACE, EGL_NO_SURFACE, EGL_NO_CONTEXT);
    eglDestroySurface(window->display, window->surface);
    window->surface = nullptr;
  }
  if (window->nativeWindow)
    ANativeWindow_release(window->nativeWindow);
  window->nativeWindow = acquireWindowLocked();

  window->surface = eglCreateWindowSurface(window->display, window->config,
                                           window->nativeWindow, nullptr);
  if (window->surface == EGL_NO_SURFACE) {
    reportError(GLFW_PLATFORM_ERROR, "eglCreateWindowSurface failed (0x%x)",
                eglGetError());
    window->surface = nullptr;
    return;
  }
  eglMakeCurrent(window->display, window->surface, window->surface, window->context);
  eglSwapInterval(window->display, window->swapInterval);
  LOGI("surface is now %dx%d", window->width, window->height);
}

/// One attribute of a config, or -1 when the driver will not say. Only used for
/// the log line: a config is chosen by what was asked for, not by reading it back.
EGLint configAttrib(EGLDisplay display, EGLConfig config, EGLint attribute) {
  EGLint value = -1;
  eglGetConfigAttrib(display, config, attribute, &value);
  return value;
}

/// Picks one EGL config, relaxing the request until the driver has something.
///
/// A single config has to serve two kinds of window: the one that owns the
/// activity's surface needs EGL_WINDOW_BIT, the offscreen children need
/// EGL_PBUFFER_BIT, and eglCreatePbufferSurface rejects a config that lacks the
/// latter with EGL_BAD_MATCH. Asking for both bits in one go is what makes that
/// work, and if a driver has no such config the caller is better served by a
/// plainer one than by no config at all.
EGLConfig chooseConfig(EGLDisplay display, const WindowHints &hints) {
  const bool wantsSamples = hints.samples > 0;
  // Dropped one at a time: the extras first, since they are the ones a driver is
  // most likely to refuse, and the colour and buffer sizes last.
  for (int relax = 0; relax < 5; ++relax) {
    std::vector<EGLint> attribs = {EGL_RENDERABLE_TYPE, EGL_OPENGL_ES3_BIT,
                                   EGL_SURFACE_TYPE, EGL_WINDOW_BIT | EGL_PBUFFER_BIT};
    if (relax < 4) {
      attribs.insert(attribs.end(), {EGL_RED_SIZE, hints.red, EGL_GREEN_SIZE,
                                     hints.green, EGL_BLUE_SIZE, hints.blue});
    }
    if (relax < 3)
      attribs.insert(attribs.end(), {EGL_ALPHA_SIZE, hints.alpha});
    if (relax < 2)
      attribs.insert(attribs.end(), {EGL_DEPTH_SIZE, hints.depth});
    if (relax < 1)
      attribs.insert(attribs.end(), {EGL_STENCIL_SIZE, hints.stencil});
    if (wantsSamples)
      attribs.insert(attribs.end(), {EGL_SAMPLES, hints.samples});
    attribs.push_back(EGL_NONE);

    EGLint count = 0;
    if (!eglChooseConfig(display, attribs.data(), nullptr, 0, &count) || count == 0)
      continue;
    std::vector<EGLConfig> configs(static_cast<size_t>(count));
    eglChooseConfig(display, attribs.data(), configs.data(), count, &count);

    // Multisampling is asked for through GLFW_SAMPLES exactly as on the desktop;
    // the config with the fewest samples that satisfies the request keeps the
    // swap chain within what the driver will allocate.
    for (EGLint i = 0; i < count; ++i) {
      EGLint got = 0;
      eglGetConfigAttrib(display, configs[static_cast<size_t>(i)], EGL_SAMPLES, &got);
      if (!wantsSamples || got <= hints.samples) {
        LOGI("EGL config %d of %d: samples=%d rgba=%d/%d/%d/%d depth=%d stencil=%d",
             i, count, got, configAttrib(display, configs[static_cast<size_t>(i)],
                                         EGL_RED_SIZE),
             configAttrib(display, configs[static_cast<size_t>(i)], EGL_GREEN_SIZE),
             configAttrib(display, configs[static_cast<size_t>(i)], EGL_BLUE_SIZE),
             configAttrib(display, configs[static_cast<size_t>(i)], EGL_ALPHA_SIZE),
             configAttrib(display, configs[static_cast<size_t>(i)], EGL_DEPTH_SIZE),
             configAttrib(display, configs[static_cast<size_t>(i)], EGL_STENCIL_SIZE));
        return configs[static_cast<size_t>(i)];
      }
    }
    return configs.front();
  }
  reportError(GLFW_PLATFORM_ERROR,
              "no EGL config with an ES3 window surface");
  return nullptr;
}

/// The process-wide EGL display, initialised on first use. Every window takes a
/// reference, released when it is destroyed; the display is terminated when the
/// last one goes.
EGLDisplay acquireDisplay() {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  if (p.display == EGL_NO_DISPLAY) {
    EGLDisplay display = eglGetDisplay(EGL_DEFAULT_DISPLAY);
    if (display == EGL_NO_DISPLAY ||
        !eglInitialize(display, &p.eglMajor, &p.eglMinor)) {
      reportError(GLFW_PLATFORM_ERROR, "eglInitialize failed (0x%x)", eglGetError());
      return EGL_NO_DISPLAY;
    }
    p.display = display;
    p.config = nullptr;
    p.configValid = false;
    LOGI("EGL %d.%d", p.eglMajor, p.eglMinor);
  }
  ++p.displayUsers;
  return p.display;
}

void releaseDisplay(EGLDisplay display) {
  if (display == EGL_NO_DISPLAY)
    return;
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  if (p.displayUsers > 0 && --p.displayUsers > 0)
    return;
  p.displayUsers = 0;
  p.config = nullptr;
  p.configValid = false;
  p.display = EGL_NO_DISPLAY;
  eglTerminate(display);
}

/// The config for these hints, picked once per display. It only depends on the
/// display and on the attributes below, and every V4D window asks for the same
/// ones, so in practice this is one eglChooseConfig for the whole process.
EGLConfig acquireConfig(EGLDisplay display, const WindowHints &hints) {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  const bool sameHints =
      p.configValid && p.configHints.samples == hints.samples &&
      p.configHints.red == hints.red && p.configHints.green == hints.green &&
      p.configHints.blue == hints.blue && p.configHints.alpha == hints.alpha &&
      p.configHints.depth == hints.depth && p.configHints.stencil == hints.stencil;
  if (sameHints && p.config)
    return p.config;
  EGLConfig config = chooseConfig(display, hints);
  p.config = config;
  p.configValid = config != nullptr;
  p.configHints = hints;
  return config;
}

void destroyWindowResources(GLFWwindow *window) {
  if (!window)
    return;
  if (window->display != EGL_NO_DISPLAY) {
    if (window->surface != EGL_NO_SURFACE)
      eglDestroySurface(window->display, window->surface);
    if (window->context != EGL_NO_CONTEXT)
      eglDestroyContext(window->display, window->context);
  }
  window->surface = nullptr;
  window->context = nullptr;
  if (window->nativeWindow)
    ANativeWindow_release(window->nativeWindow);
  window->nativeWindow = nullptr;
  releaseDisplay(window->display);
  window->display = EGL_NO_DISPLAY;
}

