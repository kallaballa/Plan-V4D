GLFWwindow *glfwCreateWindow(int width, int height, const char *, GLFWmonitor *monitor,
                             GLFWwindow *share) {
  Platform &p = platform();
  if (!p.initialized && glfwInit() != GLFW_TRUE)
    return nullptr;

  // Android hands an app exactly one window, and the activity owns its surface,
  // so only the first window can have a window surface. Every later one is a
  // child context V4D renders offscreen into -- NanoVG's, a GL context's, a
  // second plan's -- and gets an offscreen surface instead.
  //
  // This is not a workaround: an ANativeWindow can be connected to a graphics
  // API exactly once, so a second eglCreateWindowSurface() on it fails with
  // EGL_BAD_ALLOC and libEGL's real complaint,
  // "native_window_api_connect ... failed (already connected to another API?)".
  WindowHints hints;
  bool ownsSurface;
  {
    std::lock_guard<std::recursive_mutex> lock(p.mutex);
    ownsSurface = p.windows.empty();
    hints = p.hints;
  }

  ANativeWindow *nativeWindow = nullptr;
  if (ownsSurface) {
    nativeWindow = waitForNativeWindow();
    if (!nativeWindow) {
      reportError(GLFW_PLATFORM_ERROR,
                  "no surface from the activity after 10s; cannot create a window");
      return nullptr;
    }
  }

  EGLDisplay display = acquireDisplay();
  if (display == EGL_NO_DISPLAY) {
    if (nativeWindow)
      ANativeWindow_release(nativeWindow);
    return nullptr;
  }
  // OpenGL ES is the only client API Android has; binding anything else would
  // fail later with a much less obvious message.
  if (!eglBindAPI(EGL_OPENGL_ES_API)) {
    reportError(GLFW_API_UNAVAILABLE, "eglBindAPI(EGL_OPENGL_ES_API) failed");
    releaseDisplay(display);
    if (nativeWindow)
      ANativeWindow_release(nativeWindow);
    return nullptr;
  }

  EGLConfig config = acquireConfig(display, hints);
  if (!config) {
    releaseDisplay(display);
    if (nativeWindow)
      ANativeWindow_release(nativeWindow);
    return nullptr;
  }

  auto *window = new GLFWwindow();
  window->width = width > 0 ? width : (nativeWindow ? ANativeWindow_getWidth(nativeWindow) : 1);
  window->height =
      height > 0 ? height : (nativeWindow ? ANativeWindow_getHeight(nativeWindow) : 1);
  window->monitor = monitor;
  window->share = share;
  window->visible = hints.visible;
  window->resizable = hints.resizable;
  window->decorated = hints.decorated;
  window->focused = hints.focused;
  window->contextVersionMajor = hints.contextVersionMajor;
  window->contextVersionMinor = hints.contextVersionMinor;
  window->nativeWindow = nativeWindow; // the reference from waitForNativeWindow()
  window->ownsSurface = ownsSurface;
  window->display = display;
  window->config = config;

  const EGLint contextAttribs[] = {EGL_CONTEXT_CLIENT_VERSION,
                                   window->contextVersionMajor, EGL_NONE};
  window->context = eglCreateContext(
      display, config, share ? share->context : EGL_NO_CONTEXT, contextAttribs);
  if (window->context == EGL_NO_CONTEXT) {
    reportError(GLFW_API_UNAVAILABLE, "eglCreateContext failed (0x%x)", eglGetError());
    destroyWindowResources(window);
    delete window;
    return nullptr;
  }

  if (ownsSurface) {
    window->surface =
        eglCreateWindowSurface(display, config, window->nativeWindow, nullptr);
    if (window->surface == EGL_NO_SURFACE) {
      reportError(GLFW_PLATFORM_ERROR, "eglCreateWindowSurface failed (0x%x)",
                  eglGetError());
      destroyWindowResources(window);
      delete window;
      return nullptr;
    }
  } else {
    const EGLint pbufferAttribs[] = {EGL_WIDTH, window->width, EGL_HEIGHT,
                                     window->height, EGL_NONE};
    window->surface = eglCreatePbufferSurface(display, config, pbufferAttribs);
    if (window->surface == EGL_NO_SURFACE) {
      reportError(GLFW_PLATFORM_ERROR, "eglCreatePbufferSurface failed (0x%x)",
                  eglGetError());
      destroyWindowResources(window);
      delete window;
      return nullptr;
    }
  }

  // V4D creates the window from its display thread and renders there, so the
  // context is made current on this thread straight away rather than waiting for
  // an explicit glfwMakeContextCurrent().
  eglMakeCurrent(display, window->surface, window->surface, window->context);
  eglSwapInterval(display, 0);

  {
    std::lock_guard<std::recursive_mutex> lock(p.mutex);
    p.currentContext = window;
    p.windows.push_back(window);
  }
  LOGI("glfwCreateWindow: %dx%d (requested %dx%d, EGL %d.%d)%s", window->width,
       window->height, width, height, p.eglMajor, p.eglMinor,
       ownsSurface ? "" : " [offscreen]");
  return window;
}

void glfwDestroyWindow(GLFWwindow *window) {
  if (!window)
    return;
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  auto it = std::find(p.windows.begin(), p.windows.end(), window);
  if (it != p.windows.end())
    p.windows.erase(it);
  if (p.currentContext == window)
    p.currentContext = p.windows.empty() ? nullptr : p.windows.front();
  destroyWindowResources(window);
  delete window;
}

