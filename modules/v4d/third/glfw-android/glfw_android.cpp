// A GLFW-compatible implementation for Android, declared by GLFW/glfw3.h.
//
// GLFW has no Android backend. third/glfw/src/platform.c only knows WIN32,
// COCOA, WAYLAND and X11, so under the NDK toolchain there is no platform for
// glfwInit() to connect to -- and the library does not even configure, because
// its X11/Wayland backends default to ON there and then hard-require X11 headers
// that the sysroot does not ship.
//
// Rather than teach V4D about EGL at every call site, this implements the subset
// of the GLFW API that FrameBufferContext, events.hpp/gwe and the samples use on
// top of EGL + ANativeWindow + AInputQueue. The declarations sit in
// GLFW/glfw3.h next to this file (generated by
// tools/android/gen-glfw-shim-header.py) and shadow the vendored GLFW header on
// the Android include path, so no V4D source needs a #ifdef.
//
// Where the emulation is imperfect it is called out below: Android owns the
// surface, so window management and cursors are stubs, joystick enumeration
// reports nothing, and events are drained on whichever thread calls
// glfwPollEvents() -- the same rule gwe already relies on.

