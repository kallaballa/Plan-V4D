void glfwPollEvents(void) {
  Platform &p = platform();
  {
    std::lock_guard<std::recursive_mutex> lock(p.mutex);
    // Nothing to poll without an activity, and nothing worth polling while
    // backgrounded.
    if (!p.inputQueue)
      return;
  }
  pumpInput(0);
  if (p.currentContext)
    updateSizeAndNotify(p.currentContext);
}

void glfwWaitEvents(void) {
  Platform &p = platform();
  {
    std::lock_guard<std::recursive_mutex> lock(p.mutex);
    if (!p.inputQueue)
      return;
  }
  // The lock must not be held here: this blocks until an event arrives, and the
  // activity callbacks need it to publish one.
  pumpInput(-1);
  if (p.currentContext)
    updateSizeAndNotify(p.currentContext);
}

void glfwWaitEventsTimeout(double timeout) {
  Platform &p = platform();
  {
    std::lock_guard<std::recursive_mutex> lock(p.mutex);
    if (!p.inputQueue)
      return;
  }
  const int32_t millis = timeout <= 0.0 ? 0 : static_cast<int32_t>(timeout * 1000.0);
  pumpInput(millis);
  if (p.currentContext)
    updateSizeAndNotify(p.currentContext);
}

