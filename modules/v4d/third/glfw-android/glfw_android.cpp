// Long enough that a slow activity start is not mistaken for a failure, short
// enough that a genuinely surface-less process does not hang forever.
constexpr int64_t kSurfaceWaitNs = 10ll * 1000 * 1000 * 1000;

// The identifier the input queue is attached to under the looper. Any value
// works as long as it cannot collide with the other identifiers in the process;
// the NDK's native_app_glue uses 1 for the same purpose.
constexpr int kInputQueueIdent = 1;

double monotonicSeconds() {
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC, &ts);
  return static_cast<double>(ts.tv_sec) + ts.tv_nsec / 1e9;
}

