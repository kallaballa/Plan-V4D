void glfwSwapBuffers(GLFWwindow *window) {
  if (!window)
    return;
  Platform &p = platform();
  {
    std::lock_guard<std::recursive_mutex> lock(p.mutex);
    // Backgrounded: there is no surface to present to, and calling into EGL with
    // the stale one would fail on every single frame.
    if (!p.resumed)
      return;
  }
  if (!window->ownsSurface) {
    // An offscreen window has nothing to present. Swapping a pbuffer is either a
    // no-op or EGL_BAD_SURFACE depending on the driver, and either way V4D only
    // ever renders into these and reads them back, so it is skipped outright.
    return;
  }
  refreshSurface(window);
  if (!window->surface)
    return;
  updateSizeAndNotify(window);
  if (eglSwapBuffers(window->display, window->surface) != GLFW_TRUE)
    LOGW("eglSwapBuffers failed (0x%x); the surface will be rebuilt", eglGetError());
}

void glfwSwapInterval(int interval) {
  Platform &p = platform();
  std::lock_guard<std::recursive_mutex> lock(p.mutex);
  if (!p.currentContext || p.currentContext->display == EGL_NO_DISPLAY)
    return;
  p.currentContext->swapInterval = interval;
  eglSwapInterval(p.currentContext->display, interval);
}

